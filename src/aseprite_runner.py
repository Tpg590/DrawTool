"""Aseprite CLI discovery, Lua script generation, and headless export execution."""

from __future__ import annotations

import math
import os
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path


class AsepriteError(RuntimeError):
    """Raised when Aseprite CLI execution fails."""


class AsepriteNotFoundError(AsepriteError):
    """Raised when the Aseprite executable cannot be located."""


@dataclass(frozen=True)
class AsepriteResult:
    """Paths and execution logs from an Aseprite CLI packaging run."""

    aseprite_path: Path
    png_path: Path
    lua_script_path: Path
    executable: Path
    stdout: str
    stderr: str


def _candidate_aseprite_paths() -> list[Path]:
    candidates: list[Path] = []
    if os.name == "nt":
        local_app = os.environ.get("LOCALAPPDATA", "")
        prog_files = os.environ.get("ProgramFiles", r"C:\Program Files")
        prog_x86 = os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")
        candidates.extend(
            [
                Path(prog_files) / "Aseprite" / "Aseprite.exe",
                Path(prog_x86) / "Aseprite" / "Aseprite.exe",
                Path(prog_x86) / "Steam" / "steamapps" / "common" / "Aseprite" / "Aseprite.exe",
                Path(prog_files) / "Steam" / "steamapps" / "common" / "Aseprite" / "Aseprite.exe",
                Path.home() / "scoop" / "apps" / "aseprite" / "current" / "Aseprite.exe",
            ]
        )
        if local_app:
            candidates.append(Path(local_app) / "Programs" / "Aseprite" / "Aseprite.exe")
    else:
        candidates.extend(
            [
                Path("/Applications/Aseprite.app/Contents/MacOS/aseprite"),
                Path("/usr/local/bin/aseprite"),
                Path("/usr/bin/aseprite"),
                Path.home() / ".local" / "bin" / "aseprite",
            ]
        )
    return candidates


def find_aseprite(configured_path: str | None = None) -> Path:
    """Locate Aseprite CLI executable via explicit config, ASEPRITE_PATH, PATH, or default install locations."""
    for raw in (configured_path, os.environ.get("ASEPRITE_PATH")):
        if raw:
            p = Path(raw).expanduser()
            if p.is_file():
                return p.resolve()

    for cmd in ("aseprite", "Aseprite"):
        which_path = shutil.which(cmd)
        if which_path:
            return Path(which_path).resolve()

    for candidate in _candidate_aseprite_paths():
        if candidate.is_file():
            return candidate.resolve()

    raise AsepriteNotFoundError(
        "Aseprite executable was not found. Set ASEPRITE_PATH in .env (or system PATH), "
        "or pass --skip-aseprite to export processed PNG only."
    )


def _lua_quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def generate_lua_script(
    input_png: Path,
    out_aseprite: Path,
    out_png: Path,
    asset_type: str,
    frame_size: tuple[int, int],
    frames: int = 1,
    cols: int = 1,
    fps: float = 8.0,
) -> str:
    """Generate a deterministic Aseprite Lua script to create layers, timeline frames, .aseprite, and .png."""
    if fps <= 0:
        raise ValueError(f"--fps must be > 0, got {fps}")
    if frames < 1 or cols < 1:
        raise ValueError("frames and cols must both be >= 1")

    fw, fh = frame_size
    rows = math.ceil(frames / cols) if asset_type == "anim" else 1
    duration_sec = 1.0 / float(fps)

    in_png_str = _lua_quote(input_png.resolve().as_posix())
    out_ase_str = _lua_quote(out_aseprite.resolve().as_posix())
    out_png_str = _lua_quote(out_png.resolve().as_posix())
    type_str = _lua_quote(asset_type)

    return f"""-- Auto-generated by DrawTool
local INPUT_PNG = {in_png_str}
local OUT_ASEPRITE = {out_ase_str}
local OUT_PNG = {out_png_str}
local ASSET_TYPE = {type_str}
local FRAME_W = {fw}
local FRAME_H = {fh}
local FRAMES = {frames}
local COLS = {cols}
local ROWS = {rows}
local FRAME_DURATION = {duration_sec:.6f}

local srcImage = Image{{ fromFile = INPUT_PNG }}
if not srcImage then
  error("DrawTool: failed to load processed input PNG: " .. INPUT_PNG)
end

local sprite = Sprite(FRAME_W, FRAME_H, ColorMode.RGB)
local baseLayer = sprite.layers[1]
baseLayer.name = "Base"

local detailLayer = sprite:newLayer()
detailLayer.name = "Detail & Shading"

if ASSET_TYPE == "anim" then
  for i = 2, FRAMES do
    sprite:newEmptyFrame()
  end

  for i = 1, FRAMES do
    sprite.frames[i].duration = FRAME_DURATION
    local idx = i - 1
    local col = idx % COLS
    local row = math.floor(idx / COLS)
    local frameImg = Image(FRAME_W, FRAME_H, ColorMode.RGB)
    frameImg:drawImage(srcImage, Point(-col * FRAME_W, -row * FRAME_H))
    sprite:newCel(baseLayer, i, frameImg, Point(0, 0))
  end

  sprite:saveAs(OUT_ASEPRITE)
  app.command.ExportSpriteSheet{{
    ui = false,
    askOverwrite = false,
    type = SpriteSheetType.ROWS,
    columns = COLS,
    rows = ROWS,
    textureFilename = OUT_PNG,
    splitLayers = false,
    listLayers = false,
    listTags = false,
    listSlices = false,
    ignoreEmpty = false,
    mergeDuplicates = false,
    trim = false,
    openGenerated = false
  }}
else
  sprite.frames[1].duration = FRAME_DURATION
  sprite:newCel(baseLayer, 1, srcImage, Point(0, 0))
  sprite:saveAs(OUT_ASEPRITE)
  sprite:saveCopyAs(OUT_PNG)
end

sprite:close()
"""


def run_aseprite_build(
    input_png: Path,
    out_aseprite: Path,
    out_png: Path,
    asset_type: str,
    frame_size: tuple[int, int],
    frames: int = 1,
    cols: int = 1,
    fps: float = 8.0,
    configured_aseprite_path: str | None = None,
    work_dir: Path | None = None,
) -> AsepriteResult:
    """Find Aseprite, write Lua script, execute Aseprite headless (-b), and verify outputs."""
    exe = find_aseprite(configured_aseprite_path)
    out_aseprite.parent.mkdir(parents=True, exist_ok=True)
    out_png.parent.mkdir(parents=True, exist_ok=True)

    script_dir = work_dir if work_dir is not None else out_aseprite.parent
    script_dir.mkdir(parents=True, exist_ok=True)
    lua_script_path = script_dir / f"{out_aseprite.stem}_build.lua"
    lua_content = generate_lua_script(
        input_png=input_png,
        out_aseprite=out_aseprite,
        out_png=out_png,
        asset_type=asset_type,
        frame_size=frame_size,
        frames=frames,
        cols=cols,
        fps=fps,
    )
    lua_script_path.write_text(lua_content, encoding="utf-8")

    proc = subprocess.run(
        [str(exe), "-b", "--script", str(lua_script_path)],
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise AsepriteError(
            f"Aseprite failed with exit code {proc.returncode}.\n"
            f"STDOUT: {proc.stdout.strip()}\nSTDERR: {proc.stderr.strip()}"
        )
    if not out_aseprite.is_file():
        raise AsepriteError(f"Aseprite finished without producing {out_aseprite}")
    if not out_png.is_file():
        raise AsepriteError(f"Aseprite finished without producing {out_png}")

    return AsepriteResult(
        aseprite_path=out_aseprite,
        png_path=out_png,
        lua_script_path=lua_script_path,
        executable=exe,
        stdout=proc.stdout,
        stderr=proc.stderr,
    )
